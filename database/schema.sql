CREATE TABLE IF NOT EXISTS site_profile (
  id TINYINT UNSIGNED PRIMARY KEY,
  name VARCHAR(80) NOT NULL, location VARCHAR(120) NOT NULL,
  address VARCHAR(180) NOT NULL, phone VARCHAR(40) NOT NULL, hours VARCHAR(120) NOT NULL,
  story TEXT NOT NULL, demo_notice VARCHAR(220) NOT NULL,
  video_url VARCHAR(255) NOT NULL, poster_url VARCHAR(255) NOT NULL,
  video_credit_url VARCHAR(255) NOT NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS ui_texts (
  text_key VARCHAR(40) PRIMARY KEY, text_value TEXT NOT NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS sections (
  slug VARCHAR(30) PRIMARY KEY, nav_label VARCHAR(40) NOT NULL,
  eyebrow VARCHAR(80) NOT NULL, title VARCHAR(120) NOT NULL,
  description VARCHAR(300) NOT NULL, sort_order SMALLINT NOT NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS services (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, icon VARCHAR(20) NOT NULL,
  name VARCHAR(100) NOT NULL, description VARCHAR(255) NOT NULL, sort_order SMALLINT NOT NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS categories (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(60) NOT NULL, sort_order SMALLINT NOT NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS products (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  category_id INT UNSIGNED NOT NULL, name VARCHAR(100) NOT NULL,
  description VARCHAR(255) NOT NULL, price DECIMAL(8,2) UNSIGNED NOT NULL,
  featured BOOLEAN NOT NULL DEFAULT FALSE, photo_url VARCHAR(255), photo_alt VARCHAR(150),
  sort_order SMALLINT NOT NULL,
  FOREIGN KEY (category_id) REFERENCES categories(id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS gallery (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, photo_url VARCHAR(255) NOT NULL,
  photo_alt VARCHAR(150) NOT NULL, sort_order SMALLINT NOT NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS contact_messages (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL,
  email VARCHAR(254) NOT NULL, message TEXT NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
